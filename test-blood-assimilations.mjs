import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const root=new URL("./",import.meta.url),read=name=>fs.readFileSync(new URL(name,root),"utf8");
const sandbox={window:{}};vm.createContext(sandbox);vm.runInContext(read("assimilacoes-sangue.js"),sandbox);
const list=sandbox.window.ECO_BLOOD_ASSIMILATIONS;
assert.equal(list.length,30,"Sangue deve possuir exatamente 30 Assimilações");
assert.equal(new Set(list.map(item=>item.id)).size,30,"IDs devem ser únicos");
assert.ok(list.every(item=>item.element==="sangue"&&item.permanentCost?.type==="pv"),"todas precisam pertencer a Sangue e consumir PV permanente");
assert.ok(list.every(item=>item.name&&item.description&&item.activationType),"todas precisam ter regras completas");
const expected=["redencao","pungencia","hematopoiese","gula","inveja","ira","luxuria","orgulho","ganancia","elo","sangue-fervente","mutacao-reativa","surto-hematico"];
const engine=read("mesa-assimilacoes-sangue.js");expected.forEach(id=>assert.ok(engine.includes(id),`sem automação reconhecida: ${id}`));
for(const hook of ["passTableRound=function","applyPendingDamageToTarget=function","rollQuickAttack=function","rollTableCharacterSkill=function"])assert.ok(engine.includes(hook),`gancho ausente: ${hook}`);
assert.match(engine,/function ensureUnarmed/);
assert.match(engine,/amorProprioScene/);
assert.match(engine,/slug\(attack\.name\)==="desarmado"/);
assert.match(engine,/function healingNotice/);
assert.match(engine,/blood-heal-part/);
assert.match(engine,/effectiveAttribute:attr/);
assert.match(engine,/skillBonus\(character,skillName\)/);
assert.match(engine,/hematopoieseTarget/);
assert.match(engine,/openInvejaLibrary/);
assert.match(engine,/openGanancia/);
assert.match(engine,/lustInteractionBonus=4/);
for(const removed of ["empatia","olfato-rubro","vinganca","orgaos-redundantes","simbiose-carmesim","banquete-de-carne","contracao-monstruosa","pulso-carniceiro","transfusao-violenta","coracao-predador"])assert.ok(!list.some(item=>item.id===removed),`Assimilação removida ainda presente: ${removed}`);
assert.match(engine,/lists\.forEach\(list=>list\[2\]/);
assert.match(engine,/remove-element-assimilation/);
assert.match(engine,/corte:"cortante",perfuracao:"perfurante"/);
const editor=read("editor-ficha.js");
assert.match(editor,/name:"Desarmado"/);
assert.match(editor,/String\(list\[0\]\?\.damage\|\|""\)\.trim\(\)==="55"/);
assert.match(editor,/attack\$\{index\}Skill/);
assert.match(read("editor-ficha.html"),/id="attack1Skill"/);
assert.ok(read("editor-ficha.html").includes("assimilacoes-sangue.js"));
assert.ok(read("mesa.html").includes("mesa-assimilacoes-sangue.js"));
console.log(JSON.stringify({ok:true,total:list.length,unique:30,automatedHooks:4,aliases:Object.keys(sandbox.window.ECO_BLOOD_ASSIMILATION_ALIASES).length},null,2));
